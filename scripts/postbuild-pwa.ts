/**
 * Turns the Expo web export (dist/) into an installable, offline-first PWA:
 *  - dist/manifest.webmanifest
 *  - dist/sw.js: precaches the app shell and the content catalogue; caches content packs and
 *    lazy route bundles on first use; serves the app offline; never caches /api.
 *  - injects manifest, icons, theme colour, print styles and the service worker into index.html.
 */
import { readFileSync, writeFileSync, readdirSync, statSync, copyFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const root = join(__dirname, '..');
const dist = join(root, 'dist');

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const manifest = {
  name: 'Home Tutor',
  short_name: 'Home Tutor',
  description: 'Free, offline-first home learning for children aged 3 to 17.',
  start_url: '/',
  scope: '/',
  display: 'standalone',
  orientation: 'any',
  background_color: '#FFF9F0',
  theme_color: '#C2410C',
  lang: 'en',
  dir: 'auto',
  categories: ['education', 'kids'],
  icons: [
    { src: '/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: '/icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: '/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    { src: '/icon.svg', sizes: 'any', type: 'image/svg+xml' },
  ],
};
writeFileSync(join(dist, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));

const files = walk(dist).map((f) => '/' + relative(dist, f).split('\\').join('/'));
// App shell: html, the entry JS chunks referenced by index.html, icons, manifest, catalogue.
const html = readFileSync(join(dist, 'index.html'), 'utf8');
const entryScripts = [...html.matchAll(/src="([^"]+\.js)"/g)].map((m) => m[1]);
const routeChunks = files.filter((f) => f.startsWith('/_expo/static/') && !entryScripts.includes(f));
const shell = ['/', '/manifest.webmanifest', '/icon-192.png', '/icon-512.png', '/icon.svg', '/favicon.ico', '/content/catalog.json', ...entryScripts, ...routeChunks.filter((f) => f.endsWith('.js') || f.endsWith('.css'))];
const hash = createHash('sha256').update(JSON.stringify(shell)).update(html).digest('hex').slice(0, 10);

const sw = `/* Home Tutor service worker (generated by scripts/postbuild-pwa.ts) */
const VERSION = '${hash}';
const SHELL = 'ht-shell-' + VERSION;
const RUNTIME = 'ht-runtime-v1';
const PRECACHE = ${JSON.stringify(shell)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('ht-shell-') && k !== SHELL).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/')) return; // never cache the API (private data)

  if (req.mode === 'navigate') {
    // Network first so updates arrive; the cached shell keeps the app working offline.
    event.respondWith(
      fetch(req).catch(() => caches.match('/', { ignoreSearch: true }).then((r) => r || caches.match('/index.html'))),
    );
    return;
  }
  if (url.pathname.startsWith('/content/')) {
    // Stale-while-revalidate: instant offline content, refreshed in the background.
    event.respondWith(
      caches.open(RUNTIME).then(async (cache) => {
        const cached = await cache.match(req);
        const network = fetch(req)
          .then((res) => {
            if (res.ok) cache.put(req, res.clone());
            return res;
          })
          .catch(() => cached);
        return cached || network;
      }),
    );
    return;
  }
  // Hashed static files never change: cache first.
  event.respondWith(
    caches.match(req).then(
      (cached) =>
        cached ||
        fetch(req).then((res) => {
          if (res.ok && (url.pathname.startsWith('/_expo/') || url.pathname.startsWith('/assets/'))) {
            const copy = res.clone();
            caches.open(RUNTIME).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
writeFileSync(join(dist, 'sw.js'), sw);

const head = `
    <link rel="manifest" href="/manifest.webmanifest" />
    <link rel="apple-touch-icon" href="/icon-192.png" />
    <meta name="description" content="Free, offline-first home learning for children aged 3 to 17: core subjects, life skills, first aid, nature, money, languages and real projects." />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="color-scheme" content="light" />
    <style>
      body { background: #FFF9F0; }
      @media print {
        html, body { height: auto !important; overflow: visible !important; background: #fff !important; }
        #root, #root * { overflow: visible !important; }
        [data-noprint] { display: none !important; }
      }
    </style>`;
const reg = `
    <script>
      if ('serviceWorker' in navigator) {
        window.addEventListener('load', function () { navigator.serviceWorker.register('/sw.js').catch(function () {}); });
      }
    </script>`;
let out = html.replace('</head>', head + '\n  </head>').replace('</body>', reg + '\n  </body>');
out = out.replace('<noscript> You need to enable JavaScript to run this app. </noscript>', '<noscript>Home Tutor needs JavaScript. Please enable it in your browser settings.</noscript>');
writeFileSync(join(dist, 'index.html'), out);
// Static hosts without SPA fallback still serve deep links.
copyFileSync(join(dist, 'index.html'), join(dist, '404.html'));

const total = files.reduce((n, f) => n + statSync(join(dist, f)).size, 0);
console.log(`PWA ready: ${shell.length} precached files, sw ${hash}, dist ${Math.round(total / 1024)} KB`);
