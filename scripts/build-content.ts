/**
 * Builds the offline content packs:
 *  - public/content/catalog.json      light index used by the what-next engine (loaded at start)
 *  - public/content/areas/<area>.json full packs, fetched on demand and cached by the service worker
 *  - public/content/{emergency-numbers,careers}.json and languages/<code>.json
 *  - src/content-generated/index.ts   the same data bundled for native builds (works with no network)
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { AREA_IDS, type AreaPack } from '../src/core/content-types';
import { buildCatalog } from '../src/core/catalog';

const root = join(__dirname, '..');
const out = join(root, 'public', 'content');
const gen = join(root, 'src', 'content-generated');
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'areas'), { recursive: true });
mkdirSync(join(out, 'languages'), { recursive: true });
mkdirSync(gen, { recursive: true });

const packs: AreaPack[] = AREA_IDS.map((a) => JSON.parse(readFileSync(join(root, 'content', 'areas', `${a}.json`), 'utf8')));
const hash = createHash('sha256');
for (const p of packs) hash.update(JSON.stringify(p));
const extras = ['emergency-numbers', 'careers', 'books', 'photos'];
for (const e of extras) hash.update(readFileSync(join(root, 'content', `${e}.json`), 'utf8'));
const langFiles = readdirSync(join(root, 'content', 'languages')).filter((f) => f.endsWith('.json'));
for (const f of langFiles) hash.update(readFileSync(join(root, 'content', 'languages', f), 'utf8'));
const version = hash.digest('hex').slice(0, 12);

const catalog = buildCatalog(packs, version);
writeFileSync(join(out, 'catalog.json'), JSON.stringify(catalog));
for (const p of packs) writeFileSync(join(out, 'areas', `${p.area}.json`), JSON.stringify(p));
for (const e of extras) writeFileSync(join(out, `${e}.json`), JSON.stringify(JSON.parse(readFileSync(join(root, 'content', `${e}.json`), 'utf8'))));
for (const f of langFiles)
  writeFileSync(join(out, 'languages', f), JSON.stringify(JSON.parse(readFileSync(join(root, 'content', 'languages', f), 'utf8'))));

const langCodes = langFiles.map((f) => f.replace(/\.json$/, ''));
const lines = [
  '// Generated by scripts/build-content.ts. Do not edit.',
  `export const version = ${JSON.stringify(version)};`,
  `export const catalog = require('../../public/content/catalog.json');`,
  'export const packs: Record<string, any> = {',
  ...AREA_IDS.map((a) => `  ${JSON.stringify(a)}: require('../../public/content/areas/${a}.json'),`),
  '};',
  `export const emergencyNumbers = require('../../public/content/emergency-numbers.json');`,
  `export const careers = require('../../public/content/careers.json');`,
  `export const books = require('../../public/content/books.json');`,
  `export const photos = require('../../public/content/photos.json');`,
  'export const languages: Record<string, any> = {',
  ...langCodes.map((c) => `  ${JSON.stringify(c)}: require('../../public/content/languages/${c}.json'),`),
  '};',
  '',
];
writeFileSync(join(gen, 'index.ts'), lines.join('\n'));
const size = JSON.stringify(catalog).length;
console.log(`content ${version}: ${catalog.items.length} items, catalog ${Math.round(size / 1024)} KB, ${langCodes.length} languages`);
